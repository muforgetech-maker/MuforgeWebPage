-- MuForge ERP schema (PostgreSQL / Supabase).
--
-- Ported from the original SQLite schema. Two conventions are kept
-- deliberately so the application code did not have to change with it:
--
--   * calendar dates and timestamps are TEXT, not date/timestamptz. Dates are
--     'YYYY-MM-DD' and timestamps are ISO-8601 UTC, both of which compare and
--     sort correctly as text, and both of which the UI already formats.
--   * flags are INTEGER 0/1 rather than boolean, matching the CHECK
--     constraints and the values the forms submit.
--
-- Money is INTEGER paise, quantities INTEGER thousandths, tax rates INTEGER
-- basis points (1800 = 18%). Nothing here is floating point.

-- Case-insensitive email, replacing SQLite's COLLATE NOCASE on that column.
CREATE EXTENSION IF NOT EXISTS citext;

-- Timestamps are stored as ISO-8601 UTC text. One function defines that
-- format, so column defaults and application SQL cannot drift apart.
CREATE OR REPLACE FUNCTION erp_now() RETURNS text
  LANGUAGE sql STABLE
  AS $fn$ SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $fn$;

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email citext NOT NULL UNIQUE,
  name text NOT NULL,
  password_hash text NOT NULL,
  active integer NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at text NOT NULL DEFAULT erp_now(),
  last_login_at text
);

CREATE TABLE sessions (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at text NOT NULL DEFAULT erp_now(),
  expires_at text NOT NULL,
  ip text,
  user_agent text
);
CREATE INDEX sessions_user ON sessions(user_id);

CREATE TABLE login_failures (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key text NOT NULL,
  at_ms bigint NOT NULL
);
CREATE INDEX login_failures_key ON login_failures(key, at_ms);

CREATE TABLE settings (
  id integer PRIMARY KEY CHECK (id = 1),
  business_name text NOT NULL,
  legal_name text NOT NULL DEFAULT '',
  address_line1 text NOT NULL DEFAULT '',
  address_line2 text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  state_code text NOT NULL,
  pincode text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  website text NOT NULL DEFAULT '',
  gst_registered integer NOT NULL DEFAULT 0 CHECK (gst_registered IN (0, 1)),
  gstin text NOT NULL DEFAULT '',
  pan text NOT NULL DEFAULT '',
  bank_account_name text NOT NULL DEFAULT '',
  bank_account_number text NOT NULL DEFAULT '',
  bank_ifsc text NOT NULL DEFAULT '',
  bank_name text NOT NULL DEFAULT '',
  bank_branch text NOT NULL DEFAULT '',
  upi_id text NOT NULL DEFAULT '',
  invoice_prefix text NOT NULL DEFAULT 'MF',
  payment_terms_days integer NOT NULL DEFAULT 15,
  default_sac text NOT NULL DEFAULT '',
  default_tax_rate_bp integer NOT NULL DEFAULT 1800,
  round_off integer NOT NULL DEFAULT 1 CHECK (round_off IN (0, 1)),
  invoice_notes text NOT NULL DEFAULT '',
  invoice_terms text NOT NULL DEFAULT '',
  updated_at text NOT NULL DEFAULT erp_now()
);

CREATE TABLE clients (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  contact_person text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  phone text NOT NULL DEFAULT '',
  gstin text NOT NULL DEFAULT '',
  address_line1 text NOT NULL DEFAULT '',
  address_line2 text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  state_code text NOT NULL,
  pincode text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  archived integer NOT NULL DEFAULT 0 CHECK (archived IN (0, 1)),
  created_at text NOT NULL DEFAULT erp_now(),
  updated_at text NOT NULL DEFAULT erp_now()
);
CREATE INDEX clients_name ON clients(lower(name));

-- GST needs consecutive invoice numbers within each financial year.
CREATE TABLE invoice_sequences (
  financial_year text PRIMARY KEY,
  last_number integer NOT NULL
);

CREATE TABLE invoices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number text UNIQUE,
  status text NOT NULL CHECK (status IN ('draft', 'issued', 'void')),
  client_id integer NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
  issue_date text NOT NULL,
  due_date text NOT NULL,
  place_of_supply text NOT NULL,
  tax_mode text NOT NULL CHECK (tax_mode IN ('intra', 'inter', 'none')),
  subtotal_paise integer NOT NULL,
  cgst_paise integer NOT NULL,
  sgst_paise integer NOT NULL,
  igst_paise integer NOT NULL,
  round_off_paise integer NOT NULL,
  total_paise integer NOT NULL,
  notes text NOT NULL DEFAULT '',
  terms text NOT NULL DEFAULT '',
  -- JSON snapshots taken when the invoice is issued, so later edits to the
  -- client or company profile never rewrite a document already sent.
  bill_to_json text,
  seller_json text,
  issued_at text,
  voided_at text,
  void_reason text NOT NULL DEFAULT '',
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT erp_now(),
  updated_at text NOT NULL DEFAULT erp_now(),
  CHECK ((status = 'draft') = (number IS NULL))
);
CREATE INDEX invoices_client ON invoices(client_id);
CREATE INDEX invoices_status_issue ON invoices(status, issue_date);

CREATE TABLE invoice_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  position integer NOT NULL,
  description text NOT NULL,
  sac text NOT NULL DEFAULT '',
  quantity_milli integer NOT NULL CHECK (quantity_milli > 0),
  unit text NOT NULL DEFAULT '',
  rate_paise integer NOT NULL CHECK (rate_paise >= 0),
  tax_rate_bp integer NOT NULL CHECK (tax_rate_bp >= 0),
  amount_paise integer NOT NULL
);
CREATE INDEX invoice_items_invoice ON invoice_items(invoice_id, position);

CREATE TABLE payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id integer NOT NULL REFERENCES invoices(id) ON DELETE RESTRICT,
  paid_on text NOT NULL,
  amount_paise integer NOT NULL CHECK (amount_paise > 0),
  method text NOT NULL,
  reference text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT erp_now()
);
CREATE INDEX payments_invoice ON payments(invoice_id);
CREATE INDEX payments_paid_on ON payments(paid_on);

CREATE TABLE expenses (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spent_on text NOT NULL,
  category text NOT NULL,
  vendor text NOT NULL DEFAULT '',
  description text NOT NULL,
  amount_paise integer NOT NULL CHECK (amount_paise > 0),
  gst_paise integer NOT NULL DEFAULT 0 CHECK (gst_paise >= 0 AND gst_paise <= amount_paise),
  method text NOT NULL,
  reference text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT erp_now(),
  updated_at text NOT NULL DEFAULT erp_now()
);
CREATE INDEX expenses_spent_on ON expenses(spent_on);

CREATE TABLE audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at text NOT NULL DEFAULT erp_now(),
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  action text NOT NULL,
  entity text NOT NULL,
  entity_id integer,
  summary text NOT NULL DEFAULT ''
);
CREATE INDEX audit_log_at ON audit_log(at);

