-- Delivery challans, and file attachments on expenses.
--
-- A delivery challan (GST Rule 55) accompanies goods that move without an
-- invoice: job work, supply on approval, deliverables handed over before
-- billing. It carries its own consecutive series per financial year, kept
-- separate from the invoice series, and charges no tax -- the invoice that
-- follows does that.
--
-- Same conventions as the first migration: money in INTEGER paise,
-- quantities in INTEGER thousandths, dates and timestamps as TEXT.

ALTER TABLE settings
  ADD COLUMN challan_prefix text NOT NULL DEFAULT 'DC';

CREATE TABLE challan_sequences (
  financial_year text PRIMARY KEY,
  last_number integer NOT NULL
);

CREATE TABLE delivery_challans (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number text UNIQUE,
  status text NOT NULL CHECK (status IN ('draft', 'issued', 'cancelled')),
  client_id integer NOT NULL REFERENCES clients(id) ON DELETE RESTRICT,
  challan_date text NOT NULL,
  -- Rule 55 wants the purpose of the movement recorded.
  reason text NOT NULL,
  place_of_supply text NOT NULL,
  -- Optional transport details; printed only when filled in.
  vehicle_number text NOT NULL DEFAULT '',
  dispatch_through text NOT NULL DEFAULT '',
  -- Where the goods actually go, when that is not the client's own address.
  ship_to text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  terms text NOT NULL DEFAULT '',
  total_value_paise integer NOT NULL,
  -- Snapshots frozen when the challan is issued, so later edits to the
  -- client or company profile never rewrite a document already handed over.
  bill_to_json text,
  seller_json text,
  -- Set once this challan has been turned into an invoice.
  invoice_id integer REFERENCES invoices(id) ON DELETE SET NULL,
  issued_at text,
  cancelled_at text,
  cancel_reason text NOT NULL DEFAULT '',
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT erp_now(),
  updated_at text NOT NULL DEFAULT erp_now(),
  CHECK ((status = 'draft') = (number IS NULL))
);
CREATE INDEX delivery_challans_client ON delivery_challans(client_id);
CREATE INDEX delivery_challans_status_date ON delivery_challans(status, challan_date);
CREATE INDEX delivery_challans_invoice ON delivery_challans(invoice_id);

CREATE TABLE delivery_challan_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challan_id integer NOT NULL REFERENCES delivery_challans(id) ON DELETE CASCADE,
  position integer NOT NULL,
  description text NOT NULL,
  sac text NOT NULL DEFAULT '',
  quantity_milli integer NOT NULL CHECK (quantity_milli > 0),
  unit text NOT NULL DEFAULT '',
  rate_paise integer NOT NULL CHECK (rate_paise >= 0),
  amount_paise integer NOT NULL
);
CREATE INDEX delivery_challan_items_challan ON delivery_challan_items(challan_id, position);

-- Receipts and bills kept against an expense. The file itself lives in
-- Supabase Storage; only where to find it is recorded here, so the database
-- stays small and backups stay quick.
CREATE TABLE expense_attachments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_id integer NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
  storage_path text NOT NULL UNIQUE,
  file_name text NOT NULL,
  content_type text NOT NULL,
  size_bytes integer NOT NULL CHECK (size_bytes > 0),
  uploaded_by integer REFERENCES users(id) ON DELETE SET NULL,
  uploaded_at text NOT NULL DEFAULT erp_now()
);
CREATE INDEX expense_attachments_expense ON expense_attachments(expense_id, id);

-- The bucket the receipts go into. A bucket is a row, so it can be created
-- here rather than through the Storage API, which keeps a fresh deployment
-- to one migration. Private, with the size and types enforced at the
-- storage layer as well as in the application.
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'expense-attachments',
  'expense-attachments',
  false,
  10485760, -- 10 MB
  ARRAY['image/jpeg', 'image/png', 'image/webp', 'application/pdf']
) ON CONFLICT (id) DO NOTHING;

-- As with every other table: the application does its own authorisation and
-- no PostgREST access is intended.
ALTER TABLE challan_sequences ENABLE ROW LEVEL SECURITY;
ALTER TABLE delivery_challans ENABLE ROW LEVEL SECURITY;
ALTER TABLE delivery_challan_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE expense_attachments ENABLE ROW LEVEL SECURITY;
